"""Same workflow with a real PostgreSQL database in a unique disposable schema."""
import asyncio
import os
import unittest
from unittest.mock import patch
from uuid import uuid4

from fastapi.testclient import TestClient

import app
import operations
import provider
import release_registry
import storage


@unittest.skipUnless(os.getenv('TEST_DATABASE_URL'), 'PostgreSQL integration runs in its dedicated CI job')
class PostgresChecks(unittest.TestCase):
    def setUp(self):
        import psycopg
        from psycopg import sql
        self.url = os.environ['TEST_DATABASE_URL']
        self.schema = 'cap_test_' + uuid4().hex
        with psycopg.connect(self.url, autocommit=True) as conn:
            conn.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(self.schema)))
        self.environment = patch.dict(os.environ, {'DATABASE_URL': self.url, 'CAP_AVENIR_DB_SCHEMA': self.schema})
        self.environment.start()
        storage.init_db()

    def tearDown(self):
        import psycopg
        from psycopg import sql
        self.environment.stop()
        # The namespace is generated by this test, never an application schema.
        assert self.schema.startswith('cap_test_') and len(self.schema) == 41
        with psycopg.connect(self.url, autocommit=True) as conn:
            conn.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(self.schema)))

    def test_workflow_events_costs_and_controls(self):
        async def fake(agent, profile, dossiers=None, scenario='normal'):
            await asyncio.sleep(.01)
            if agent == 'supervisor':
                self.assertIn('summary', dossiers['evolution'])
                self.assertIn('summary', dossiers['reconversion'])
            return {'summary': agent, 'recommendation': 'Fixture'}, {'cost': .01, 'prompt_tokens': 10, 'completion_tokens': 5}

        with TestClient(app.app) as client, patch.object(provider, 'demo_agent', fake):
            response = client.post('/api/runs', json={'profile': {'situation': 'Développeur junior', 'skills': 'Python'}, 'mode': 'demo'})
            self.assertEqual(response.status_code, 202)
            import time
            deadline = time.monotonic() + 10
            while time.monotonic() < deadline:
                run = client.get('/api/runs/' + response.json()['id']).json()
                if run['status'] != 'running':
                    break
                time.sleep(.05)
            self.assertEqual(run['status'], 'completed')
            self.assertEqual(run['tokens'], 45)
            self.assertAlmostEqual(run['cost'], .03)
            self.assertTrue(run['events'])
            self.assertTrue(all(e['run_id'] == run['id'] for e in run['events']))
            self.assertTrue(storage.add_alert(run['id'], 'workflow', 'fixture', 'Test'))
            self.assertFalse(storage.add_alert(run['id'], 'workflow', 'fixture', 'Test'))
            operations.change_pause(True, 'Test PostgreSQL', 'Pause persistante')
            storage.init_db()
            self.assertTrue(operations.get_state()['paused'])

    def test_registry_and_backup_persist_outside_local_files(self):
        image_id = 'sha256:' + 'a' * 64
        release_registry.register('1.2.0', 'example:1.2.0', image_id)
        release_registry.review('1.2.0', 'approved', 'Test PostgreSQL', card_reviewed=True)
        self.assertEqual(release_registry.approved('1.2.0', image_id)['status'], 'approved')
        with TestClient(app.app) as client:
            result = client.post('/api/ops/backup', json={'actor': 'Test PostgreSQL'})
            self.assertEqual(result.status_code, 200)
            self.assertEqual(result.json()['format'], 'application-json')
            storage.init_db()
            backup = client.get(result.json()['download'])
            self.assertEqual(backup.status_code, 200)
            self.assertEqual(backup.json()['operations']['releases']['candidates'][0]['version'], '1.2.0')

    def test_render_restart_keeps_pause_and_audits_deployment_once(self):
        environment = {'RENDER': 'true', 'CAP_AVENIR_ADMIN_PASSWORD': 'cloud-test',
                       'RENDER_GIT_COMMIT': 'a' * 40, 'RENDER_SERVICE_ID': 'srv-test'}
        with patch.dict(os.environ, environment):
            with TestClient(app.app) as client:
                result = client.post('/api/ops/pause', json={'paused': True, 'actor': 'Test Render'}, auth=('admin', 'cloud-test'))
                self.assertEqual(result.status_code, 200)
            with TestClient(app.app) as restarted:
                self.assertEqual(restarted.get('/api/ops').status_code, 401)
                snapshot = restarted.get('/api/ops', auth=('admin', 'cloud-test')).json()
                self.assertTrue(snapshot['paused'])
                self.assertEqual(snapshot['platform'], 'render')
                self.assertEqual(snapshot['database'], 'postgresql')
                self.assertEqual(len(snapshot['releases']['deployments']), 1)
